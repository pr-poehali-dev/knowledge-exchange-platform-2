export type UserRole = 'student' | 'teacher';
export type RankTier = 'Нулёвый' | 'Любопытный' | 'Дебаггер' | 'Хакер' | 'Синтаксис' | 'Компилятор' | 'Архитектор' | 'Оракул';

export interface User {
  id: number;
  name: string;
  avatar: string;
  role: UserRole;
  rank: RankTier;
  rating: number;
  answersCount: number;
  likesReceived: number;
  subject?: string;
  bio?: string;
  achievements: Achievement[];
}

export interface Achievement {
  id: number;
  title: string;
  icon: string;
  description: string;
  unlocked: boolean;
}

export interface Question {
  id: number;
  title: string;
  body: string;
  category: string;
  tags: string[];
  authorId: number;
  createdAt: string;
  views: number;
  answersCount: number;
  answers: Answer[];
}

export interface Answer {
  id: number;
  body: string;
  authorId: number;
  createdAt: string;
  likes: number;
  isAccepted: boolean;
}

export interface Notification {
  id: number;
  type: 'like' | 'answer' | 'achievement';
  text: string;
  time: string;
  read: boolean;
}

